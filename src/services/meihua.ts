/**
 * 分析体用五行关系
 * Analyze body-use five-element relationship
 *
 * 梅花易数以体卦为主（求测者/事物），用卦为客（外部环境/变化因素）。
 * 通过五行生克判断事情的吉凶趋势。
 *
 * In Plum Blossom numerology, the body hexagram represents the querent,
 * and the use hexagram represents external factors.
 * Five-element relationships determine fortune trends.
 *
 * @param bodyTrigram 体卦的经卦
 * @param useTrigram 用卦的经卦
 * @param month 当前月份（1-12，用于判断卦气旺衰）
 * @returns 五行分析结果
 */
export function analyzeWuXing(
  bodyTrigram: BaGua,
  useTrigram: BaGua,
  month: number
): WuXingAnalysis {
  const bodyElement = BAGUA_WUXING_MAP[bodyTrigram];
  const useElement = BAGUA_WUXING_MAP[useTrigram];
  const bodyElementEN = BAGUA_WUXING_MAP_EN[getBaGuaByNumberEN(
    Object.entries(BAGUA_NUMBER_MAP).find(([, v]) => v === bodyTrigram)?.[0]
      ? Number(Object.entries(BAGUA_NUMBER_MAP).find(([, v]) => v === bodyTrigram)![0])
      : 1
  )] || 'Metal';
  const useElementEN = BAGUA_WUXING_MAP_EN[getBaGuaByNumberEN(
    Object.entries(BAGUA_NUMBER_MAP).find(([, v]) => v === useTrigram)?.[0]
      ? Number(Object.entries(BAGUA_NUMBER_MAP).find(([, v]) => v === useTrigram)![0])
      : 1
  )] || 'Metal';

  // 获取五行关系
  const relationKey = WUXING_RELATION_MATRIX[bodyElement][useElement];
  let relation: WuXingAnalysis['relation'];
  let relationEN: WuXingAnalysis['relationEN'];

  switch (relationKey) {
    case '生':
      relation = '生';
      relationEN = 'generates';
      break;
    case '克':
      relation = '克';
      relationEN = 'destroys';
      break;
    case '被生':
      relation = '被生';
      relationEN = 'generated by';
      break;
    case '被克':
      relation = '被克';
      relationEN = 'destroyed by';
      break;
    default:
      relation = '同';
      relationEN = 'same';
  }

  // 获取季节旺衰
  const season = getSeasonByMonth(month);
  const bodyState = getElementSeasonalState(bodyElement, season);
  const bodyStateEN = getElementSeasonalStateEN(bodyElement, season);
  const useState = getElementSeasonalState(useElement, season);
  const useStateEN = getElementSeasonalStateEN(useElement, season);

  // 生成解读
  const interpretation = generateWuXingInterpretation(
    bodyElement, useElement, relation, bodyState, useState
  );
  const interpretationEN = generateWuXingInterpretationEN(
    bodyElementEN, useElementEN, relationEN, bodyStateEN, useStateEN
  );

  return {
    bodyElement,
    bodyElementEN,
    useElement,
    useElementEN,
    relation,
    relationEN,
    bodySeasonalState: bodyState,
    bodySeasonalStateEN: bodyStateEN,
    useSeasonalState: useState,
    useSeasonalStateEN: useStateEN,
    interpretation,
    interpretationEN,
  };
}

