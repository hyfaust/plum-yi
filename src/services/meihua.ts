// ==================== 基础工具函数 Basic Utility Functions ====================

/**
 * 生成随机数（用于随机起卦）
 * Generate random number (for random divination)
 * @param min 最小值
 * @param max 最大值
 * @returns 随机整数
 */
export function generateRandomNumber(min: number, max: number): number {
  return Math.floor(Math.random() * (max - min + 1)) + min;
}

/**
 * 计算数字除以8的余数（先天八卦数）
 * Calculate number mod 8 (Earlier Heaven bagua number)
 * @param number 输入数字
 * @returns 1-8的数字（0视为8）
 */
export function calculateMod8(number: number): number {
  const remainder = number % 8;
  return remainder === 0 ? 8 : remainder;
}

/**
 * 计算数字除以6的余数（用于动爻）
 * Calculate number mod 6 (for moving line)
 * @param number 输入数字
 * @returns 1-6的数字（0视为6）
 */
export function calculateMod6(number: number): number {
  const remainder = number % 6;
  return remainder === 0 ? 6 : remainder;
}

/**
 * 根据数字生成爻
 * Generate Yao line based on number
 * @param number 输入数字
 * @param isMoving 是否为动爻
 * @param position 爻的位置
 * @returns Yao对象
 */
export function generateYao(number: number, isMoving: boolean, position: number): Yao {
  // 奇数为阳爻，偶数为阴爻
  const isYang = number % 2 !== 0;
  return {
    line: isYang ? '阳' : '阴',
    lineEN: isYang ? 'Yang' : 'Yin',
    number,
    isMoving,
    position,
  };
}

/**
 * 根据数字生成三爻卦（经卦）
 * Generate trigram based on number
 * @param number 1-8的数字
 * @returns 三爻数组
 */
export function generateTrigramLines(number: number): [YaoLine, YaoLine, YaoLine] {
  // 先天八卦二进制表示（从下到上）
  const trigramBinary: Record<number, [YaoLine, YaoLine, YaoLine]> = {
    1: ['阳', '阳', '阳'],  // 乾 ☰
    2: ['阳', '阳', '阴'],  // 兑 ☱
    3: ['阳', '阴', '阳'],  // 离 ☲
    4: ['阳', '阴', '阴'],  // 震 ☳
    5: ['阴', '阳', '阳'],  // 巽 ☴
    6: ['阴', '阳', '阴'],  // 坎 ☵
    7: ['阴', '阴', '阳'],  // 艮 ☶
    8: ['阴', '阴', '阴'],  // 坤 ☷
  };
  
  const normalizedNumber = calculateMod8(number);
  return trigramBinary[normalizedNumber];
}

/**
 * 生成六爻卦
 * Generate hexagram lines
 * @param upperNumber 上卦数字
 * @param lowerNumber 下卦数字
 * @param movingLine 动爻位置（1-6）
 * @returns 六爻数组
 */
export function generateHexagramLines(
  upperNumber: number,
  lowerNumber: number,
  movingLine: number
): Yao[] {
  const lines: Yao[] = [];
  
  // 生成下卦三爻（1-3爻）
  const lowerTrigramLines = generateTrigramLines(lowerNumber);
  for (let i = 0; i < 3; i++) {
    lines.push({
      line: lowerTrigramLines[i],
      lineEN: lowerTrigramLines[i] === '阳' ? 'Yang' : 'Yin',
      number: lowerNumber,
      isMoving: i + 1 === movingLine,
      position: i + 1,
    });
  }
  
  // 生成上卦三爻（4-6爻）
  const upperTrigramLines = generateTrigramLines(upperNumber);
  for (let i = 0; i < 3; i++) {
    lines.push({
      line: upperTrigramLines[i],
      lineEN: upperTrigramLines[i] === '阳' ? 'Yang' : 'Yin',
      number: upperNumber,
      isMoving: i + 4 === movingLine,
      position: i + 4,
    });
  }
  
  return lines;
}

/**
 * 生成卦象对象
 * Generate hexagram object
 * @param upperNumber 上卦数字
 * @param lowerNumber 下卦数字
 * @param movingLine 动爻位置
 * @returns GuaXiang对象
 */
export function generateGuaXiang(
  upperNumber: number,
  lowerNumber: number,
  movingLine: number
): GuaXiang {
  const upperTrigram = getBaGuaByNumber(upperNumber);
  const lowerTrigram = getBaGuaByNumber(lowerNumber);
  const upperTrigramEN = getBaGuaByNumberEN(upperNumber);
  const lowerTrigramEN = getBaGuaByNumberEN(lowerNumber);
  
  const lines = generateHexagramLines(upperNumber, lowerNumber, movingLine);
  
  // 卦的五行属性取下卦（体卦）的五行
  const element = getBaGuaElement(lowerTrigram);
  const elementEN = getBaGuaElementEN(lowerTrigramEN);
  
  // 生成二进制表示（从下到上）
  const binary = lines.map(l => l.line === '阳' ? '1' : '0').join('');
  
  // 简化的卦名生成（实际应用中可能需要完整的64卦名称表）
  const name = `${upperTrigram}上${lowerTrigram}下`;
  const nameEN = `${upperTrigramEN} over ${lowerTrigramEN}`;
  
  return {
    name,
    nameEN,
    upperTrigram,
    upperTrigramEN,
    lowerTrigram,
    lowerTrigramEN,
    lines,
    element,
    elementEN,
    number: upperNumber * 10 + lowerNumber, // 简化的卦序
    binary,
  };
}

// ==================== 起卦方法 Divination Methods ====================

/**
 * 农历年份数字映射（地支序号）
 * Lunar year number mapping (Earthly Branch index)
 * 梅花易数中，年的数字取地支序号：子=1, 丑=2, ..., 亥=12
 * In Plum Blossom, year number uses Earthly Branch: Zi=1, Chou=2, ..., Hai=12
 */
export function getYearBranchNumber(year: number): number {
  // 地支序号：子(1), 丑(2), 寅(3), 卯(4), 辰(5), 巳(6),
  //           午(7), 未(8), 申(9), 酉(10), 戌(11), 亥(12)
  // 公历年转地支：(year - 4) % 12 + 1
  return ((year - 4) % 12) + 1;
}

/**
 * 时间起卦法
 * Time-based divination method
 *
 * 算法说明 / Algorithm description:
 * 上卦 G_u = (年支数 + 月数 + 日数) mod 8
 * 下卦 G_l = (年支数 + 月数 + 日数 + 时支数) mod 8
 * 动爻 M = (年支数 + 月数 + 日数 + 时支数) mod 6
 *
 * Upper trigram: G_u = (YearBranch + Month + Day) mod 8
 * Lower trigram: G_l = (YearBranch + Month + Day + HourBranch) mod 6
 * Moving line:   M   = (YearBranch + Month + Day + HourBranch) mod 6
 *
 * 时辰与地支对应：
 * 子时(23-01)=1, 丑时(01-03)=2, 寅时(03-05)=3, 卯时(05-07)=4,
 * 辰时(07-09)=5, 巳时(09-11)=6, 午时(11-13)=7, 未时(13-15)=8,
 * 申时(15-17)=9, 酉时(17-19)=10, 戌时(19-21)=11, 亥时(21-23)=12
 *
 * @param year 公历年份
 * @param month 月份（1-12）
 * @param day 日期（1-31）
 * @param hour 小时（0-23）
 * @returns 起卦结果
 */
export function divinationByTime(
  year: number,
  month: number,
  day: number,
  hour: number
): DivinationResult {
  // 获取年支数
  const yearBranch = getYearBranchNumber(year);

  // 获取时辰数（小时转地支序号）
  // 子时(23-01)=1, 丑时(01-03)=2, ..., 亥时(21-23)=12
  const hourBranch = Math.floor(((hour + 1) % 24) / 2) + 1;

  // 计算上卦数字和
  const upperSum = yearBranch + month + day;
  // 计算下卦数字和（包含时辰）
  const lowerSum = upperSum + hourBranch;

  // 上卦：数字和 mod 8
  const upperNumber = calculateMod8(upperSum);
  // 下卦：数字和（含时辰）mod 8
  const lowerNumber = calculateMod8(lowerSum);
  // 动爻：总和 mod 6
  const movingLine = calculateMod6(lowerSum);

  // 生成主卦
  const mainGua = generateGuaXiang(upperNumber, lowerNumber, movingLine);

  // 确定体用卦
  const { bodyGua, useGua, bodyTrigram, useTrigram } = determineBodyUse(mainGua, movingLine);

  // 计算互卦
  const mutualGua = calculateMutualGua(mainGua);

  // 计算变卦
  const changedGua = calculateChangedGua(mainGua, movingLine);

  return {
    method: '时间起卦',
    methodEN: 'Time',
    timestamp: new Date(year, month - 1, day, hour),
    input: { year, month, day, hour, yearBranch, hourBranch },
    mainGua,
    mutualGua,
    changedGua,
    movingLine,
    bodyGua,
    useGua,
    bodyTrigram,
    useTrigram,
  };
}

/**
 * 数字起卦法
 * Number-based divination method
 *
 * 算法说明 / Algorithm description:
 * - 取第一个数 mod 8 为上卦
 * - 取第二个数 mod 8 为下卦
 * - 两数之和 mod 6 为动爻
 * - 如果只有一个数，则该数 mod 8 为上卦，该数 mod 8 为下卦（取余后加1作为下卦）
 *
 * Upper trigram: N_1 mod 8
 * Lower trigram: N_2 mod 8
 * Moving line:   (N_1 + N_2) mod 6
 *
 * @param num1 第一个数字
 * @param num2 第二个数字（可选，缺省等于 num1）
 * @returns 起卦结果
 */
export function divinationByNumber(num1: number, num2?: number): DivinationResult {
  const n1 = Math.abs(Math.floor(num1));
  const n2 = num2 !== undefined ? Math.abs(Math.floor(num2)) : n1;

  const upperNumber = calculateMod8(n1);
  const lowerNumber = calculateMod8(n2);
  const movingLine = calculateMod6(n1 + n2);

  const mainGua = generateGuaXiang(upperNumber, lowerNumber, movingLine);
  const { bodyGua, useGua, bodyTrigram, useTrigram } = determineBodyUse(mainGua, movingLine);
  const mutualGua = calculateMutualGua(mainGua);
  const changedGua = calculateChangedGua(mainGua, movingLine);

  return {
    method: '数字起卦',
    methodEN: 'Number',
    timestamp: new Date(),
    input: { num1: n1, num2: n2 },
    mainGua,
    mutualGua,
    changedGua,
    movingLine,
    bodyGua,
    useGua,
    bodyTrigram,
    useTrigram,
  };
}

/**
 * 文字起卦法（笔画起卦法）
 * Text-based divination method (stroke count method)
 *
 * 算法说明 / Algorithm description:
 * - 单字：总笔画 mod 8 为上卦，总笔画 mod 8 为下卦，总笔画 mod 6 为动爻
 * - 双字：第一字笔画 mod 8 为上卦，第二字笔画 mod 8 为下卦，总笔画 mod 6 为动爻
 * - 多字：前半笔画之和 mod 8 为上卦，后半笔画之和 mod 8 为下卦，总笔画 mod 6 为动爻
 *
 * 注意：此函数接受笔画数数组，笔画数的获取需要调用方提供。
 * Note: This function accepts stroke count arrays. Getting actual stroke counts
 * requires an external Chinese character stroke dictionary.
 *
 * @param strokeCounts 文字笔画数数组
 * @param text 原始文字（仅用于记录）
 * @returns 起卦结果
 */
export function divinationByText(strokeCounts: number[], text?: string): DivinationResult {
  if (strokeCounts.length === 0) {
    throw new Error('文字起卦需要至少一个字的笔画数 / Text divination requires at least one stroke count');
  }

  let upperSum: number;
  let lowerSum: number;
  let totalSum: number;

  if (strokeCounts.length === 1) {
    // 单字：笔画数同时用于上下卦
    upperSum = strokeCounts[0];
    lowerSum = strokeCounts[0];
    totalSum = strokeCounts[0];
  } else if (strokeCounts.length === 2) {
    // 双字：第一字为上卦，第二字为下卦
    upperSum = strokeCounts[0];
    lowerSum = strokeCounts[1];
    totalSum = strokeCounts[0] + strokeCounts[1];
  } else {
    // 多字：前半为上卦，后半为下卦
    const mid = Math.ceil(strokeCounts.length / 2);
    upperSum = strokeCounts.slice(0, mid).reduce((a, b) => a + b, 0);
    lowerSum = strokeCounts.slice(mid).reduce((a, b) => a + b, 0);
    totalSum = strokeCounts.reduce((a, b) => a + b, 0);
  }

  const upperNumber = calculateMod8(upperSum);
  const lowerNumber = calculateMod8(lowerSum);
  const movingLine = calculateMod6(totalSum);

  const mainGua = generateGuaXiang(upperNumber, lowerNumber, movingLine);
  const { bodyGua, useGua, bodyTrigram, useTrigram } = determineBodyUse(mainGua, movingLine);
  const mutualGua = calculateMutualGua(mainGua);
  const changedGua = calculateChangedGua(mainGua, movingLine);

  return {
    method: '文字起卦',
    methodEN: 'Text',
    timestamp: new Date(),
    input: { text: text || '', strokeCounts },
    mainGua,
    mutualGua,
    changedGua,
    movingLine,
    bodyGua,
    useGua,
    bodyTrigram,
    useTrigram,
  };
}

