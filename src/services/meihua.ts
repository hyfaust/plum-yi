// ==================== 体用关系 Body-Use Relationship ====================

/**
 * 确定体卦和用卦
 * Determine body (ti) and use (yong) hexagrams
 *
 * 规则 / Rules:
 * - 动爻在下卦（1-3爻）：下卦为用卦，上卦为体卦
 * - 动爻在上卦（4-6爻）：上卦为用卦，下卦为体卦
 *
 * If moving line is in lower trigram (lines 1-3):
 *   lower trigram = use, upper trigram = body
 * If moving line is in upper trigram (lines 4-6):
 *   upper trigram = use, lower trigram = body
 *
 * @param mainGua 主卦
 * @param movingLine 动爻位置（1-6）
 * @returns 体用卦信息
 */
export function determineBodyUse(
  mainGua: GuaXiang,
  movingLine: number
): {
  bodyGua: GuaXiang;
  useGua: GuaXiang;
  bodyTrigram: BaGua;
  useTrigram: BaGua;
} {
  const isMovingInLower = movingLine <= 3;

  // 体卦：不动的经卦  Body: the trigram without the moving line
  // 用卦：有动爻的经卦  Use: the trigram with the moving line
  const bodyTrigram = isMovingInLower ? mainGua.upperTrigram : mainGua.lowerTrigram;
  const useTrigram = isMovingInLower ? mainGua.lowerTrigram : mainGua.upperTrigram;

  // 体用卦本质上与主卦相同，只是关注点不同
  const bodyGua = { ...mainGua };
  const useGua = { ...mainGua };

  return {
    bodyGua,
    useGua,
    bodyTrigram,
    useTrigram,
  };
}

// ==================== 互卦与变卦 Mutual and Changed Hexagrams ====================

/**
 * 计算互卦
 * Calculate mutual hexagram (hu gua)
 *
 * 互卦算法 / Mutual hexagram algorithm:
 * 取主卦的第2、3、4爻为互卦的下卦
 * 取主卦的第3、4、5爻为互卦的上卦
 *
 * Lower trigram of mutual: lines 2, 3, 4 of main hexagram
 * Upper trigram of mutual: lines 3, 4, 5 of main hexagram
 *
 * @param mainGua 主卦
 * @returns 互卦
 */
export function calculateMutualGua(mainGua: GuaXiang): GuaXiang {
  const lines = mainGua.lines;

  // 互卦下卦：取主卦第2、3、4爻
  // Mutual lower trigram: lines 2, 3, 4
  const mutualLower: YaoLine[] = [lines[1].line, lines[2].line, lines[3].line];

  // 互卦上卦：取主卦第3、4、5爻
  // Mutual upper trigram: lines 3, 4, 5
  const mutualUpper: YaoLine[] = [lines[2].line, lines[3].line, lines[4].line];

  // 根据爻线反推八卦数字
  const lowerNumber = trigramLinesToNumber(mutualLower);
  const upperNumber = trigramLinesToNumber(mutualUpper);

  // 互卦没有动爻，动爻位置设为0
  return generateGuaXiang(upperNumber, lowerNumber, 0);
}

/**
 * 计算变卦
 * Calculate changed hexagram (bian gua)
 *
 * 变卦算法 / Changed hexagram algorithm:
 * 将主卦的动爻阴阳互变（阳变阴，阴变阳），其余爻不变。
 *
 * Flip the moving line (Yang<->Yin), keep other lines unchanged.
 *
 * @param mainGua 主卦
 * @param movingLine 动爻位置（1-6）
 * @returns 变卦
 */
export function calculateChangedGua(mainGua: GuaXiang, movingLine: number): GuaXiang {
  const lines = mainGua.lines.map((yao, index) => {
    if (index + 1 === movingLine) {
      // 动爻变：阳变阴，阴变阳
      // Flip moving line: Yang->Yin, Yin->Yang
      return {
        ...yao,
        line: yao.line === '阳' ? '阴' as YaoLine : '阳' as YaoLine,
        lineEN: yao.line === '阳' ? 'Yin' as YaoLineEN : 'Yang' as YaoLineEN,
        isMoving: true,
      };
    }
    return { ...yao, isMoving: false };
  });

  // 从变爻后的新线路反推上下卦数字
  const changedLower: YaoLine[] = [lines[0].line, lines[1].line, lines[2].line];
  const changedUpper: YaoLine[] = [lines[3].line, lines[4].line, lines[5].line];

  const lowerNumber = trigramLinesToNumber(changedLower);
  const upperNumber = trigramLinesToNumber(changedUpper);

  const changed = generateGuaXiang(upperNumber, lowerNumber, 0);
  // 保留原始的变爻信息
  changed.lines = lines;

  return changed;
}

/**
 * 根据三爻线反推八卦数字
 * Infer trigram number from three Yao lines
 *
 * @param lines 三爻数组（从下到上）
 * @returns 1-8 的八卦数字
 */
export function trigramLinesToNumber(lines: YaoLine[]): number {
  // 先天八卦二进制到数字映射（从下到上）
  const binaryToNumber: Record<string, number> = {
    '111': 1,  // 乾
    '110': 2,  // 兑
    '101': 3,  // 离
    '100': 4,  // 震
    '011': 5,  // 巽
    '010': 6,  // 坎
    '001': 7,  // 艮
    '000': 8,  // 坤
  };

  const binary = lines.map(l => l === '阳' ? '1' : '0').join('');
  return binaryToNumber[binary] || 1;
}

