// ==================== 综合断卦 Comprehensive Interpretation ====================

/**
 * 综合断卦
 * Comprehensive hexagram interpretation
 *
 * 整合主卦、互卦、变卦的五行关系，结合体用关系和卦气旺衰，
 * 给出综合性的判断和建议。
 *
 * Integrates five-element relationships of main, mutual, and changed hexagrams,
 * combined with body-use relationships and seasonal states,
 * to provide comprehensive judgment and advice.
 *
 * @param divinationResult 起卦结果
 * @param month 当前月份（1-12）
 * @returns 综合断卦结果
 */
export function comprehensiveInterpretation(
  divinationResult: DivinationResult,
  month: number
): ComprehensiveInterpretation {
  // 分析主卦体用五行关系
  const wuxingAnalysis = analyzeWuXing(
    divinationResult.bodyTrigram,
    divinationResult.useTrigram,
    month
  );

  // 分析互卦五行关系（互卦显示事情发展的过程）
  const mutualAnalysis = divinationResult.mutualGua
    ? analyzeWuXing(
        divinationResult.mutualGua.lowerTrigram,
        divinationResult.mutualGua.upperTrigram,
        month
      )
    : null;

  // 分析变卦五行关系（变卦显示事情的最终结果）
  const changedAnalysis = divinationResult.changedGua
    ? analyzeWuXing(
        divinationResult.changedGua.lowerTrigram,
        divinationResult.changedGua.upperTrigram,
        month
      )
    : null;

  // 综合判断
  const overallResult = generateOverallInterpretation(
    wuxingAnalysis,
    mutualAnalysis,
    changedAnalysis
  );

  // 生成各方面预测
  const aspects = generateAspectPredictions(wuxingAnalysis, divinationResult);

  return {
    divinationResult,
    wuxingAnalysis,
    overallInterpretation: overallResult.chinese,
    overallInterpretationEN: overallResult.english,
    advice: overallResult.advice,
    adviceEN: overallResult.adviceEN,
    confidence: overallResult.confidence,
    aspects,
  };
}

/**
 * 生成综合解读
 * Generate overall interpretation
 */
function generateOverallInterpretation(
  mainAnalysis: WuXingAnalysis,
  mutualAnalysis: WuXingAnalysis | null,
  changedAnalysis: WuXingAnalysis | null
): {
  chinese: string;
  english: string;
  advice: string;
  adviceEN: string;
  confidence: number;
} {
  // 吉凶判断基础逻辑
  // Auspiciousness determination logic
  let fortune: '吉' | '凶' | '平';
  let fortuneEN: 'Auspicious' | 'Inauspicious' | 'Neutral';

  // 体卦被生最吉，体卦生用泄气次吉，比和为平，体克用小凶，体被克最凶
  // Body generated by use is most auspicious, body generates use is second,
  // same element is neutral, body destroys use is slightly inauspicious,
  // body destroyed by use is most inauspicious
  switch (mainAnalysis.relation) {
    case '被生':
      fortune = '吉';
      fortuneEN = 'Auspicious';
      break;
    case '生':
      fortune = '平';
      fortuneEN = 'Neutral';
      break;
    case '同':
      fortune = '平';
      fortuneEN = 'Neutral';
      break;
    case '克':
      fortune = '平';
      fortuneEN = 'Neutral';
      break;
    case '被克':
      fortune = '凶';
      fortuneEN = 'Inauspicious';
      break;
  }

  // 结合卦气旺衰调整
  // Adjust based on seasonal state
  if (mainAnalysis.bodySeasonalState === '旺' || mainAnalysis.bodySeasonalState === '相') {
    // 体卦得令，加分
    if (fortune === '凶') fortune = '平';
    if (fortune === '平') fortune = '吉';
  } else if (mainAnalysis.bodySeasonalState === '死' || mainAnalysis.bodySeasonalState === '囚') {
    // 体卦失令，减分
    if (fortune === '吉') fortune = '平';
    if (fortune === '平') fortune = '凶';
  }

  // 构建解读文本
  const fortuneText = fortune === '吉' ? '吉利' : fortune === '凶' ? '不利' : '平稳';
  const fortuneTextEN = fortuneEN;

  let chinese = `【综合断卦】${fortuneText}。${mainAnalysis.interpretation}`;
  let english = `[Overall] ${fortuneTextEN}. ${mainAnalysis.interpretationEN}`;

  // 如果有互卦分析，添加过程描述
  if (mutualAnalysis) {
    chinese += `事情发展过程中，${mutualAnalysis.interpretation}`;
    english += ` During development, ${mutualAnalysis.interpretationEN}`;
  }

  // 如果有变卦分析，添加结果描述
  if (changedAnalysis) {
    chinese += `最终结果趋向：${changedAnalysis.interpretation}`;
    english += ` Final outcome tends toward: ${changedAnalysis.interpretationEN}`;
  }

  // 生成建议
  let advice: string;
  let adviceEN: string;

  switch (fortune) {
    case '吉':
      advice = '此卦吉利，宜积极进取，把握时机。体卦得势，做事容易成功，但也要注意不要过于冒进。';
      adviceEN = 'This hexagram is auspicious. Take initiative and seize opportunities. The body hexagram is strong, making success likely, but avoid being overly aggressive.';
      break;
    case '凶':
      advice = '此卦不利，宜谨慎守成，静观其变。体卦受制，做事容易遇到阻碍，建议等待时机或调整策略。';
      adviceEN = 'This hexagram is inauspicious. Be cautious and observe changes. The body hexagram is suppressed, indicating obstacles. Consider waiting for better timing or adjusting strategy.';
      break;
    default:
      advice = '此卦平稳，宜稳中求进。没有明显的吉凶倾向，按部就班，循序渐进即可。';
      adviceEN = 'This hexagram is neutral. Progress steadily. There is no clear auspicious or inauspicious tendency — proceed step by step.';
  }

  // 计算置信度
  // Confidence based on body state strength
  let confidence = 60; // 基础置信度
  if (mainAnalysis.bodySeasonalState === '旺') confidence += 20;
  else if (mainAnalysis.bodySeasonalState === '相') confidence += 10;
  else if (mainAnalysis.bodySeasonalState === '死') confidence -= 10;
  else if (mainAnalysis.bodySeasonalState === '囚') confidence -= 5;

  // 如果互卦和变卦分析一致，增加置信度
  if (mutualAnalysis && changedAnalysis) {
    if (mutualAnalysis.relation === mainAnalysis.relation &&
        changedAnalysis.relation === mainAnalysis.relation) {
      confidence += 10;
    }
  }

  confidence = Math.max(30, Math.min(95, confidence));

  return {
    chinese,
    english,
    advice,
    adviceEN,
    confidence,
  };
}

